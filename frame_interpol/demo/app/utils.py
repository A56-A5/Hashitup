import os
from PIL import Image, ImageDraw, ImageFont
from dotenv import load_dotenv

load_dotenv()

def generate_future_prediction(image_path, year):
    # For now, this function just draws text on the image
    # Later, this will be replaced with AI prediction logic

    img = Image.open(image_path).convert("RGB")
    draw = ImageDraw.Draw(img)

    try:
        # Try to use a truetype font if available
        font = ImageFont.truetype("arial.ttf", 40)
    except IOError:
        # Fallback to a default PIL font if truetype is not found
        font = ImageFont.load_default()

    text = f"Prediction {year}"
    text_width, text_height = draw.textsize(text, font=font)
    
    # Position text at the bottom center
    width, height = img.size
    x = (width - text_width) / 2
    y = height - text_height - 10  # 10 pixels from the bottom

    draw.text((x, y), text, font=font, fill=(255, 255, 255)) # White text

    output_dir = os.path.join(os.path.dirname(image_path), "predictions")
    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, f"prediction_{year}_{os.path.basename(image_path)}")
    img.save(output_path)

    return output_path

